// Builds BlazonGuild/Locales/<lang>.lua from the translations: i18n/source.json is the frozen list of Spanish texts
// (tests/i18n-keys.mjs), and i18n/<lang>/NN.json the translations of texts NN*250 .. NN*250+249, in that order.
// Each language also has its dates (days, months, and how a date is written). Run: node tests/i18n-build.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
export const LANGS = ['en', 'de', 'fr', 'it', 'pt', 'ru'];
export const CHUNK = 250;

const DATES = {
  en: { days: ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'],
    months: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
    format: 'return day .. " " .. n .. " " .. month' },
  de: { days: ['Sonntag', 'Montag', 'Dienstag', 'Mittwoch', 'Donnerstag', 'Freitag', 'Samstag'],
    months: ['Januar', 'Februar', 'März', 'April', 'Mai', 'Juni', 'Juli', 'August', 'September', 'Oktober', 'November', 'Dezember'],
    format: 'return day .. ", " .. n .. ". " .. month' },
  fr: { days: ['dimanche', 'lundi', 'mardi', 'mercredi', 'jeudi', 'vendredi', 'samedi'],
    months: ['janvier', 'février', 'mars', 'avril', 'mai', 'juin', 'juillet', 'août', 'septembre', 'octobre', 'novembre', 'décembre'],
    format: 'return day .. " " .. n .. " " .. month' },
  it: { days: ['domenica', 'lunedì', 'martedì', 'mercoledì', 'giovedì', 'venerdì', 'sabato'],
    months: ['gennaio', 'febbraio', 'marzo', 'aprile', 'maggio', 'giugno', 'luglio', 'agosto', 'settembre', 'ottobre', 'novembre', 'dicembre'],
    format: 'return day .. " " .. n .. " " .. month' },
  pt: { days: ['domingo', 'segunda-feira', 'terça-feira', 'quarta-feira', 'quinta-feira', 'sexta-feira', 'sábado'],
    months: ['janeiro', 'fevereiro', 'março', 'abril', 'maio', 'junho', 'julho', 'agosto', 'setembro', 'outubro', 'novembro', 'dezembro'],
    format: 'return day .. ", " .. n .. " de " .. month' },
  ru: { days: ['воскресенье', 'понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота'],
    months: ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'],
    format: 'return day .. ", " .. n .. " " .. month' },
};

const lua = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '') + '"';

export function translations(lang) {
  const source = JSON.parse(readFileSync(join(ROOT, 'i18n', 'source.json'), 'utf8'));
  const dir = join(ROOT, 'i18n', lang);
  const map = new Map();
  if (!existsSync(dir)) return { source, map };
  for (const f of readdirSync(dir).filter((x) => /^\d+\.json$/.test(x)).sort()) {
    const base = parseInt(f, 10) * CHUNK;
    const arr = JSON.parse(readFileSync(join(dir, f), 'utf8'));
    arr.forEach((t, i) => {
      const key = source[base + i];
      if (key !== undefined && typeof t === 'string' && t !== '') map.set(key, t);
    });
  }
  return { source, map };
}

// The text of BlazonGuild/Locales/<lang>.lua (tests/locales.mjs checks the file is this).
export function luaFor(lang) {
  const { map } = translations(lang);
  const d = DATES[lang];
  const lines = [
    `-- ${lang}: generated by tests/i18n-build.mjs from i18n/${lang}/*.json (do not edit by hand: edit those, then build).`,
    'local _, BG = ...',
    'BG.Locales = BG.Locales or {}',
    `BG.Locales.${lang} = { date = { days = { ${d.days.map(lua).join(', ')} },`,
    `  months = { ${d.months.map(lua).join(', ')} },`,
    `  format = function(day, n, month) ${d.format} end }, strings = {`,
  ];
  for (const [k, v] of [...map.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) lines.push(`  [${lua(k)}] = ${lua(v)},`);
  lines.push('} }', '');
  return { text: lines.join('\n'), size: map.size };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = JSON.parse(readFileSync(join(ROOT, 'i18n', 'source.json'), 'utf8'));
  for (const lang of LANGS) {
    const { text, size } = luaFor(lang);
    writeFileSync(join(ROOT, 'BlazonGuild', 'Locales', `${lang}.lua`), text);
    console.log(`${lang}: ${size} de ${source.length}`);
  }
}
